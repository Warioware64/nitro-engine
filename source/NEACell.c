{
    NEA_AssertPointer(data, "NULL data");
    NEA_AssertPointer(name, "NULL name");

    for (int i = 0; i < data->num_multicells; i++)
    {
        if (strncmp(data->multicells[i].name, name,
                    sizeof(data->multicells[i].name)) == 0)
            return i;
    }
    return -1;
}

int NEA_CellSequenceTicks(const NEA_CellData *data, int seq)
{
    NEA_AssertPointer(data, "NULL data");
    if (seq < 0 || seq >= data->num_sequences)
        return 0;
    int ticks = data->sequences[seq].total_ticks;
    return ticks > 0 ? ticks : 1;
}

int NEA_CellGetBounds(const NEA_CellData *data, int cell,
                      int *min_x, int *min_y, int *max_x, int *max_y)
{
    NEA_AssertPointer(data, "NULL data");
    if (cell < 0 || cell >= data->num_cells)
        return -1;

    const NEA_CellCell *c = &data->cells[cell];
    if (min_x)
        *min_x = c->min_x;
    if (min_y)
        *min_y = c->min_y;
    if (max_x)
        *max_x = c->max_x;
    if (max_y)
        *max_y = c->max_y;
    return 0;
}

