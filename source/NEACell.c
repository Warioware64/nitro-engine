void NEA_CellAnimUpdate(NEA_CellAnim *anim)
{
    NEA_AssertPointer(anim, "NULL animation");
    if (anim->data == NULL)
        return;

    if (anim->playing && !anim->finished)
        anim->currtick += anim->speed;

    // Advance the nodes before evaluating, because the parent's evaluate is
    // what re-poses them: doing it the other way round leaves every node one
    // tick behind the entity it belongs to.
    for (int i = 0; i < anim->num_children; i++)
    {
        NEA_CellAnim *child = anim->children[i];
        if (child && child->playing && !child->finished)
            child->currtick += child->speed;
    }

    NEA_CellAnimEvaluate(anim);
}

void NEA_CellAnimUpdateAll(void)
{
    if (!ne_cell_system_inited)
        return;

    for (int i = 0; i < ne_cell_max_anims; i++)
    {
        NEA_CellAnim *anim = ne_cell_anims[i];
        // Multi-cell nodes are advanced by their parent. Stepping them here
        // as well would run them at double speed.
        if (anim && anim->active && anim->data && !anim->is_child)
            NEA_CellAnimUpdate(anim);
    }
}
