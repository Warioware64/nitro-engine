int NEA_CellSystemReset(int max_anims)
{
    if (ne_cell_system_inited)
        NEA_CellSystemEnd();

    if (max_anims < 1)
        max_anims = NEA_DEFAULT_CELL_ANIMS;

    ne_cell_anims = calloc(max_anims, sizeof(NEA_CellAnim *));
    if (ne_cell_anims == NULL)
    {
        NEA_DebugPrint("NEACell: not enough memory");
        return -1;
    }

    ne_cell_max_anims = max_anims;
    ne_cell_system_inited = true;
    return 0;
}

void NEA_CellSystemEnd(void)
{
    if (!ne_cell_system_inited)
        return;

    NEA_CellAnimDeleteAll();

    free(ne_cell_anims);
    ne_cell_anims = NULL;
    ne_cell_max_anims = 0;
    ne_cell_system_inited = false;
    __ne_cell_camera = NULL;
}

NEA_CellAnim *NEA_CellAnimCreate(void)
{
    if (!ne_cell_system_inited)
    {
        NEA_DebugPrint("NEACell: system not initialized");
        return NULL;
    }

    for (int i = 0; i < ne_cell_max_anims; i++)
    {
        if (ne_cell_anims[i] != NULL)
            continue;

        NEA_CellAnim *anim = calloc(1, sizeof(NEA_CellAnim));
        if (anim == NULL)
        {
            NEA_DebugPrint("NEACell: not enough memory");
            return NULL;
        }

        anim->active = true;
        anim->speed = 1 << 12;
        anim->scale_x = 1 << 12;
        anim->scale_y = 1 << 12;
        anim->base_alpha = 31;
        anim->base_color = 0x7FFF;
        anim->units_per_pixel = floattof32(1.0f / 32.0f);
        anim->anchor = NEA_CELL_ANCHOR_CENTER;
        anim->sequence = NE_CELL_SEQ_NONE;
        anim->multicell = 0xFFFF;

        ne_cell_anims[i] = anim;
        return anim;
    }

    NEA_DebugPrint("NEACell: no free animation slots");
    return NULL;
}

static void ne_cell_release_children(NEA_CellAnim *anim)
{
    if (anim->children == NULL)
        return;
    for (int i = 0; i < anim->num_children; i++)
    {
        if (anim->children[i])
            NEA_CellAnimDelete(anim->children[i]);
    }
    free(anim->children);
    anim->children = NULL;
    anim->num_children = 0;
    anim->multicell = 0xFFFF;
}

void NEA_CellAnimDelete(NEA_CellAnim *anim)
{
    if (anim == NULL)
        return;

    // Weak reference: the hardware backend is a separate translation unit, so
    // a ROM that never bound OAM never links it and this resolves to NULL.
    extern void NEA_CellAnimUnbindOAM(NEA_CellAnim *anim) __attribute__((weak));
    if (anim->oam && NEA_CellAnimUnbindOAM)
        NEA_CellAnimUnbindOAM(anim);

    ne_cell_release_children(anim);

    free(anim->pose);
    free(anim->xform_scratch);

    for (int i = 0; i < ne_cell_max_anims; i++)
    {
        if (ne_cell_anims[i] == anim)
        {
            ne_cell_anims[i] = NULL;
            break;
        }
    }

    free(anim);
}

void NEA_CellAnimDeleteAll(void)
{
    if (ne_cell_anims == NULL)
        return;
    for (int i = 0; i < ne_cell_max_anims; i++)
    {
        if (ne_cell_anims[i])
            NEA_CellAnimDelete(ne_cell_anims[i]);
    }
}

int NEA_CellAnimSetData(NEA_CellAnim *anim, const NEA_CellData *data)
{
    NEA_AssertPointer(anim, "NULL animation");
    NEA_AssertPointer(data, "NULL data");

    ne_cell_release_children(anim);

    // The pose and the scratch transforms are sized for the largest cell in
    // the bank, once, so playback never allocates.
    int capacity = data->max_parts_any_cell;
    if (capacity < 1)
        capacity = 1;

    NEA_CellPartXform *pose = calloc(capacity, sizeof(NEA_CellPartXform));
    ne_xform_t *scratch = calloc(capacity, sizeof(ne_xform_t));
    if (pose == NULL || scratch == NULL)
    {
        free(pose);
        free(scratch);
        NEA_DebugPrint("NEACell: not enough memory for a pose buffer");
        return -1;
    }

    free(anim->pose);
    free(anim->xform_scratch);
    anim->pose = pose;
    anim->xform_scratch = scratch;
    anim->pose_capacity = capacity;
    anim->pose_count = 0;

    anim->data = data;
    anim->sequence = NE_CELL_SEQ_NONE;
    anim->currtick = 0;
    anim->playing = false;
    anim->finished = false;
    return 0;
}

int NEA_CellAnimPlay(NEA_CellAnim *anim, int seq, int32_t speed)
{
    NEA_AssertPointer(anim, "NULL animation");
    if (anim->data == NULL)
        return -1;
    if (seq < 0 || seq >= anim->data->num_sequences)
    {
        NEA_DebugPrint("NEACell: sequence %d is out of range", seq);
        return -1;
    }

    // A CELL or RIG sequence has no nodes, so drop any the instance was
    // holding from an earlier multi-cell.
    if (anim->data->sequences[seq].kind != NEA_CELL_KIND_MULTI)
        ne_cell_release_children(anim);

    anim->sequence = seq;
    anim->currtick = 0;
    anim->playing = true;
    anim->finished = false;
    if (speed != 0)
        anim->speed = speed;

    NEA_CellAnimEvaluate(anim);
    return 0;
}

int NEA_CellAnimPlayNamed(NEA_CellAnim *anim, const char *name, int32_t speed)
{
    NEA_AssertPointer(anim, "NULL animation");
    if (anim->data == NULL)
        return -1;

    int seq = NEA_CellFindSequence(anim->data, name);
    if (seq < 0)
    {
        NEA_DebugPrint("NEACell: no sequence named '%s'", name);
        return -1;
    }
    return NEA_CellAnimPlay(anim, seq, speed);
}

// Seat one child instance per node of a multi-cell.
//
// Each child keeps its own clock, which is the whole point: a looping cape and
// a one-shot sword swing belong to one entity without being resampled onto a
// shared frame counter.
static int ne_cell_seat_multicell(NEA_CellAnim *anim, int multicell)
{
    const NEA_CellData *data = anim->data;
    if (data == NULL || multicell < 0 || multicell >= data->num_multicells)
        return -1;

    ne_cell_release_children(anim);

    const NEA_CellMultiCell *mc = &data->multicells[multicell];
    if (mc->num_nodes == 0)
        return 0;

    anim->children = calloc(mc->num_nodes, sizeof(NEA_CellAnim *));
    if (anim->children == NULL)
    {
        NEA_DebugPrint("NEACell: not enough memory for multi-cell nodes");
        return -1;
    }

    for (int i = 0; i < mc->num_nodes; i++)
    {
        const NEA_CellNode *node = &data->nodes[mc->first_node + i];

        NEA_CellAnim *child = NEA_CellAnimCreate();
        if (child == NULL)
        {
            NEA_DebugPrint("NEACell: ran out of slots seating a multi-cell");
            break;
        }
        anim->children[i] = child;
        anim->num_children = i + 1;

        if (NEA_CellAnimSetData(child, data) != 0)
            break;

        child->is_child = true;
        child->node_x = node->x;
        child->node_y = node->y;
        child->node_priority = node->priority;
        child->anchor = anim->anchor;
        NEA_CellAnimPlay(child, node->seq, anim->speed);
        if (node->flags & 1)
            child->playing = false;

        // If the parent is already bound to the hardware backend, the child
        // has to be too -- otherwise seating a multi-cell after binding
        // silently produces an entity that draws as quads but not as sprites.
        // Weak reference: NEACellOAM.c is only linked when something binds.
        extern void __NEA_CellBindChildOAM(NEA_CellAnim *, NEA_CellAnim *)
            __attribute__((weak));
        if (anim->oam && __NEA_CellBindChildOAM)
            __NEA_CellBindChildOAM(anim, child);
    }

    anim->multicell = multicell;
    return 0;
}

int NEA_CellAnimPlayMulti(NEA_CellAnim *anim, int multicell)
{
    NEA_AssertPointer(anim, "NULL animation");
    if (anim->data == NULL)
        return -1;

    if (ne_cell_seat_multicell(anim, multicell) != 0)
        return -1;

    anim->sequence = NE_CELL_SEQ_NONE;
    anim->currtick = 0;
    anim->playing = true;
    anim->finished = false;
    anim->multi_px = 0;
    anim->multi_py = 0;
    return 0;
}

