int NEA_CellFindSequence(const NEA_CellData *data, const char *name)
{
    NEA_AssertPointer(data, "NULL data");
    NEA_AssertPointer(name, "NULL name");

    for (int i = 0; i < data->num_sequences; i++)
    {
        if (strncmp(data->sequences[i].name, name,
                    sizeof(data->sequences[i].name)) == 0)
            return i;
    }
    return -1;
}

