static const void *ne_cell_find_section(const uint8_t *base,
                                        const ne_cell_header_t *hdr,
                                        uint32_t tag, uint32_t *count)
{
    const ne_cell_section_t *dir =
        (const ne_cell_section_t *)(base + sizeof(ne_cell_header_t));

    for (int i = 0; i < hdr->num_sections; i++)
    {
        if (dir[i].tag != tag)
            continue;
        if (dir[i].offset + 4 > hdr->file_size)
            return NULL;
        const uint8_t *payload = base + dir[i].offset;
        if (count)
            *count = *(const uint32_t *)payload;
        return payload + 4;
    }

    if (count)
        *count = 0;
    return NULL;
}

// The frame lookup is a binary search over per-sequence prefix sums of the
// frame durations. Building them here costs one pass at load; not building
// them would cost a walk of the frame list on every evaluation of every
// instance, which is the one part of this that runs 60 times a second.
static bool ne_cell_build_prefix(NEA_CellData *data)
{
    uint32_t total = 0;
    for (int i = 0; i < data->num_sequences; i++)
        total += (uint32_t)data->sequences[i].num_frames + 1;

    if (total == 0)
        return true;

    data->seq_prefix = calloc(total, sizeof(uint16_t));
    data->seq_prefix_base = calloc(data->num_sequences, sizeof(uint16_t));
    if (data->seq_prefix == NULL || data->seq_prefix_base == NULL)
        return false;

    uint32_t at = 0;
    for (int i = 0; i < data->num_sequences; i++)
    {
        const NEA_CellSequence *seq = &data->sequences[i];
        data->seq_prefix_base[i] = at;
        uint16_t acc = 0;
        data->seq_prefix[at++] = 0;
        for (int f = 0; f < seq->num_frames; f++)
        {
            uint16_t dur = data->frames[seq->first_frame + f].duration;
            acc += dur ? dur : 1;
            data->seq_prefix[at++] = acc;
        }
    }
    return true;
}

// A child part reads its parent's finished transform straight out of the
// scratch array, which only works if parents come first. Rejecting a file that
// breaks that here means the evaluator never has to check.
static bool ne_cell_validate(const NEA_CellData *data)
{
    for (int c = 0; c < data->num_cells; c++)
    {
        const NEA_CellCell *cell = &data->cells[c];
        if ((uint32_t)cell->first_part + cell->num_parts > data->num_parts)
        {
            NEA_DebugPrint("NEACell: cell %d runs past the part pool", c);
            return false;
        }
        for (int p = 0; p < cell->num_parts; p++)
        {
            const NEA_CellPart *part = &data->parts[cell->first_part + p];
            if (part->parent >= p)
            {
                NEA_DebugPrint("NEACell: cell %d part %d parents forward", c, p);
                return false;
            }
            if (part->atlas >= data->num_atlases)
            {
                NEA_DebugPrint("NEACell: cell %d part %d: bad atlas", c, p);
                return false;
            }
        }
    }

    for (int s = 0; s < data->num_sequences; s++)
    {
        const NEA_CellSequence *seq = &data->sequences[s];
        if ((uint32_t)seq->first_frame + seq->num_frames > data->num_frames)
        {
            NEA_DebugPrint("NEACell: sequence %d runs past the frame pool", s);
            return false;
        }
        if ((uint32_t)seq->first_track + seq->num_tracks > data->num_tracks)
        {
            NEA_DebugPrint("NEACell: sequence %d runs past the track pool", s);
            return false;
        }
        if (seq->kind == NEA_CELL_KIND_RIG && seq->cell >= data->num_cells)
        {
            NEA_DebugPrint("NEACell: sequence %d: bad rig cell", s);
            return false;
        }
    }

    return true;
}

NEA_CellData *NEA_CellDataLoad(const void *pointer)
{
    NEA_AssertPointer(pointer, "NULL pointer");

    const uint8_t *base = pointer;
    const ne_cell_header_t *hdr = pointer;

    if (hdr->magic != NEA_CELL_MAGIC)
    {
        NEA_DebugPrint("NEACell: bad magic 0x%08lX", (unsigned long)hdr->magic);
        return NULL;
    }
    if (hdr->version != NEA_CELL_VERSION)
    {
        NEA_DebugPrint("NEACell: unsupported version %d", hdr->version);
        return NULL;
    }

    NEA_CellData *data = calloc(1, sizeof(NEA_CellData));
    if (data == NULL)
    {
        NEA_DebugPrint("NEACell: not enough memory");
        return NULL;
    }

    data->flags = hdr->flags;

    uint32_t count = 0;
    data->atlases = ne_cell_find_section(base, hdr, TAG_ATLS, &count);
    data->num_atlases = count;
    data->cells = ne_cell_find_section(base, hdr, TAG_CELS, &count);
    data->num_cells = count;
    data->parts = ne_cell_find_section(base, hdr, TAG_PART, &count);
    data->num_parts = count;
    data->sequences = ne_cell_find_section(base, hdr, TAG_SEQS, &count);
    data->num_sequences = count;
    data->frames = ne_cell_find_section(base, hdr, TAG_FRMS, &count);
    data->num_frames = count;
    data->tracks = ne_cell_find_section(base, hdr, TAG_TRKS, &count);
    data->num_tracks = count;
    data->keys = ne_cell_find_section(base, hdr, TAG_KEYS, &count);
    data->multicells = ne_cell_find_section(base, hdr, TAG_MCEL, &count);
    data->num_multicells = count;
    data->nodes = ne_cell_find_section(base, hdr, TAG_NODE, &count);
    data->num_nodes = count;
    data->budget = ne_cell_find_section(base, hdr, TAG_BUDG, &count);

    if (data->cells == NULL || data->parts == NULL || data->sequences == NULL)
    {
        NEA_DebugPrint("NEACell: file is missing a required section");
        free(data);
        return NULL;
    }

    if (!ne_cell_validate(data))
    {
        free(data);
        return NULL;
    }

    for (int c = 0; c < data->num_cells; c++)
    {
        if (data->cells[c].num_parts > data->max_parts_any_cell)
            data->max_parts_any_cell = data->cells[c].num_parts;
    }

    if (data->num_atlases > 0)
    {
        data->atlas_mat = calloc(data->num_atlases, sizeof(NEA_Material *));
        if (data->atlas_mat == NULL)
        {
            free(data);
            return NULL;
        }
    }

    if (!ne_cell_build_prefix(data))
    {
        free(data->seq_prefix);
        free(data->seq_prefix_base);
        free(data->atlas_mat);
        free(data);
        return NULL;
    }

    return data;
}

NEA_CellData *NEA_CellDataLoadFAT(const char *path)
{
    NEA_AssertPointer(path, "NULL path");

    void *buffer = NEA_FATLoadData(path);
    if (buffer == NULL)
    {
        NEA_DebugPrint("NEACell: couldn't read %s", path);
        return NULL;
    }

    NEA_CellData *data = NEA_CellDataLoad(buffer);
    if (data == NULL)
    {
        free(buffer);
        return NULL;
    }

    data->_base_data = buffer;
    data->_loaded_from_fat = true;
    return data;
}

void NEA_CellDataFree(NEA_CellData *data)
{
    if (data == NULL)
        return;

    // An instance left pointing at freed data would evaluate garbage on the
    // next VBL, so cut them loose first.
    for (int i = 0; i < ne_cell_max_anims; i++)
    {
        NEA_CellAnim *anim = ne_cell_anims ? ne_cell_anims[i] : NULL;
        if (anim && anim->data == data)
        {
            NEA_CellAnimStop(anim);
            anim->data = NULL;
            anim->pose_count = 0;
        }
    }

    free(data->atlas_mat);
    free(data->seq_prefix);
    free(data->seq_prefix_base);
    if (data->_loaded_from_fat)
        free(data->_base_data);
    free(data);
}

int NEA_CellDataBindMaterials(NEA_CellData *data)
{
    NEA_AssertPointer(data, "NULL data");

    int missing = 0;
    for (int i = 0; i < data->num_atlases; i++)
    {
        NEA_Material *mat = NEA_MaterialFindByName(data->atlases[i].name);
        data->atlas_mat[i] = mat;
        if (mat == NULL)
        {
            NEA_DebugPrint("NEACell: no material named '%s'",
                           data->atlases[i].name);
            missing++;
        }
    }
    return missing;
}

int NEA_CellDataSetMaterial(NEA_CellData *data, int atlas, NEA_Material *mat)
{
    NEA_AssertPointer(data, "NULL data");
    if (atlas < 0 || atlas >= data->num_atlases)
        return -1;
    data->atlas_mat[atlas] = mat;
    return 0;
}

