# Generates the cross-check vectors for the AnimMat evaluator.
#
# The editor's live preview is only honest if animmat_format.py evaluates an
# animation exactly the way NEAAnimMat.c does. Nothing enforces that on its own,
# and a drift between the two would show up as a preview that quietly disagrees
# with the hardware -- the worst kind of bug for an authoring tool.
#
# So this writes two files from one source of truth: the .neaanimmat binary, and
# a C table of what the Python evaluator says every frame of it should be. The
# test ROM loads the binary, evaluates it with the real runtime, and compares.
# If the two implementations ever diverge, the ROM says which frame and which
# track.

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "animmat_editor"))

import animmat_format as A  # noqa: E402

NUM_FRAMES = 64

# Deliberately awkward: every storage mode, every interpolation mode, and the
# track types whose lerp is not a plain linear one (packed colours, the wrapping
# angle, the clamped alpha).
ANIM = {
    "num_frames": NUM_FRAMES,
    "targets": [
        {
            "name": "body",
            "tracks": [
                # Keyframed, linear, clamped at both ends.
                {"type": A.ALPHA, "storage": A.STORE_KEYS,
                 "interp": A.INTERP_LINEAR,
                 "keys": [[0, 31], [17, 3], [40, 24], [63, 31]]},

                # Keyframed, per-channel colour lerp with uneven spacing.
                {"type": A.COLOR, "storage": A.STORE_KEYS,
                 "interp": A.INTERP_LINEAR,
                 "keys": [[0, 0x7FFF], [9, 0x001F], [37, 0x7C00], [63, 0x03E0]]},

                # Packed dual colour: the one shape that cannot be baked.
                {"type": A.DIFFUSE_AMBIENT, "storage": A.STORE_KEYS,
                 "interp": A.INTERP_LINEAR,
                 "keys": [[0, 0x294A7FFF], [31, 0x00000421],
                          [63, 0x7FFF294A]]},

                # Step, never interpolated.
                {"type": A.LIGHTS, "storage": A.STORE_KEYS,
                 "interp": A.INTERP_STEP,
                 "keys": [[0, 0x1], [12, 0x3], [33, 0xF], [55, 0x1]]},

                # Constant: no array, no search.
                {"type": A.CULLING, "storage": A.STORE_CONST, "value": 0x80},
            ],
        },
        {
            "name": "trim",
            "tracks": [
                # Baked 1.10.5, including negative values.
                {"type": A.TEX_SCROLL_X, "storage": A.STORE_BAKED,
                 "values": [((f * 37) % 512) - 256 for f in range(NUM_FRAMES)]},

                # Baked, and read back as a plain unsigned 16 bit value.
                {"type": A.TEX_ROTATE, "storage": A.STORE_BAKED,
                 "values": [(f * 8) % 512 for f in range(NUM_FRAMES)]},

                # Keyframed angle, which wraps rather than clamps.
                {"type": A.TEX_SCALE_Y, "storage": A.STORE_KEYS,
                 "interp": A.INTERP_LINEAR,
                 "keys": [[0, A.f32(1.0)], [30, A.f32(2.5)],
                          [63, A.f32(0.25)]]},

                # Step swap with the "leave this one alone" sentinel.
                {"type": A.TEXPAL_SWAP, "storage": A.STORE_KEYS,
                 "interp": A.INTERP_STEP,
                 "keys": [[0, 0x00FF], [20, 0x0102], [44, 0xFF01]]},
            ],
        },
    ],
}


def main():
    data_dir = os.path.join(HERE, "data")
    src_dir = os.path.join(HERE, "source")
    os.makedirs(data_dir, exist_ok=True)

    blob = A.dumps(ANIM)
    with open(os.path.join(data_dir, "vectors.bin"), "wb") as f:
        f.write(blob)

    lines = [
        "// Generated by gen_vectors.py. Do not edit.",
        "//",
        "// Expected output of the AnimMat evaluator, produced by the Python",
        "// implementation in tools/animmat_editor/animmat_format.py. The test",
        "// ROM checks the C runtime against these values frame by frame.",
        "",
        "#ifndef ANIMMAT_VECTORS_H__",
        "#define ANIMMAT_VECTORS_H__",
        "",
        "#include <stdint.h>",
        "",
        f"#define VEC_NUM_FRAMES  {NUM_FRAMES}",
        f"#define VEC_NUM_TARGETS {len(ANIM['targets'])}",
        "",
        "typedef struct {",
        "    uint8_t  track_type;",
        "    uint32_t values[VEC_NUM_FRAMES];",
        "} vec_track_t;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    int num_tracks;",
        "    const vec_track_t *tracks;",
        "} vec_target_t;",
        "",
    ]

    total = 0
    for ti, target in enumerate(ANIM["targets"]):
        lines.append(f"static const vec_track_t vec_tracks_{ti}[] = {{")
        for track in target["tracks"]:
            vals = [A.evaluate_track(track, f << 12) for f in range(NUM_FRAMES)]
            total += len(vals)
            body = ", ".join(f"0x{v:08X}" for v in vals)
            lines.append(f"    {{ {track['type']}, {{ {body} }} }},")
        lines.append("};")
        lines.append("")

    lines.append("static const vec_target_t vec_targets[] = {")
    for ti, target in enumerate(ANIM["targets"]):
        n = len(target["tracks"])
        lines.append(f'    {{ "{target["name"]}", {n}, vec_tracks_{ti} }},')
    lines.append("};")
    lines.append("")
    lines.append("#endif // ANIMMAT_VECTORS_H__")

    with open(os.path.join(src_dir, "vectors.h"), "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"vectors.bin: {len(blob)} bytes")
    print(f"vectors.h:   {total} expected values "
          f"({len(ANIM['targets'])} targets, {NUM_FRAMES} frames)")


if __name__ == "__main__":
    main()
